#!/usr/bin/env python3
"""Install licensed, local Halo brand fonts without network access.

Usage:
  python scripts/brand/install_fonts.py \
    --sora-regular path/Sora-Regular.ttf \
    --sora-semibold path/Sora-SemiBold.ttf \
    --atkinson-regular path/AtkinsonHyperlegibleNext-Regular.ttf \
    --atkinson-medium path/AtkinsonHyperlegibleNext-Medium.ttf \
    --atkinson-bold path/AtkinsonHyperlegibleNext-Bold.ttf \
    --sora-license path/OFL-Sora.txt \
    --atkinson-license path/OFL-Atkinson.txt

Requires: pip install fonttools. The script does not download fonts or
overwrite licenses without supplied original files.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

REPO = Path(__file__).resolve().parents[2]
DEST = REPO / "app/src/main/res/font"
LICENCES = REPO / "app/src/main/assets/licenses"
BRAND_FONTS = REPO / "app/src/main/java/com/halo/app/ui/theme/BrandFonts.kt"


def validate_font(source: Path, family: str) -> None:
    if not source.is_file() or source.suffix.lower() not in (".ttf", ".otf"):
        raise ValueError(f"Expected a local TTF/OTF file for {family}: {source}")
    if source.stat().st_size < 1000 or source.stat().st_size > 10_000_000:
        raise ValueError(f"Unexpected font size: {source}")
    try:
        from fontTools.ttLib import TTFont
    except ImportError as e:
        raise RuntimeError("Install fonttools to inspect family metadata: pip install fonttools") from e
    font = TTFont(source, lazy=True)
    try:
        names = {
            rec.toUnicode().casefold()
            for rec in font["name"].names
            if rec.nameID in (1, 4, 6, 16)
        }
        if not any(family.casefold() in name.replace("-", " ") for name in names):
            raise ValueError(f"Font family is not {family}: {source} ({sorted(names)[:6]})")
    finally:
        font.close()


def validate_license(path: Path) -> None:
    if not path.is_file():
        raise ValueError(f"Missing license: {path}")
    text = path.read_text(encoding="utf-8-sig")
    if "SIL OPEN FONT LICENSE" not in text.upper() or len(text) < 500:
        raise ValueError(f"Expected complete SIL Open Font License: {path}")


def generated_typefaces() -> str:
    return """package com.halo.app.ui.theme

import androidx.compose.ui.text.font.Font
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import com.halo.app.R

/** Bundled local Sora and Atkinson Hyperlegible Next fonts.
 *  Generated by scripts/brand/install_fonts.py; do not hand-edit.
 */
object HaloBrandFonts {
    val display: FontFamily = FontFamily(
        Font(R.font.sora_regular, FontWeight.Normal),
        Font(R.font.sora_semibold, FontWeight.SemiBold),
    )
    val reading: FontFamily = FontFamily(
        Font(R.font.atkinson_regular, FontWeight.Normal),
        Font(R.font.atkinson_medium, FontWeight.Medium),
        Font(R.font.atkinson_bold, FontWeight.Bold),
    )
}
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    for flag in (
        "sora_regular", "sora_semibold", "atkinson_regular",
        "atkinson_medium", "atkinson_bold", "sora_license", "atkinson_license"
    ):
        parser.add_argument("--" + flag.replace("_", "-"), type=Path, required=True)
    args = parser.parse_args()
    pairs = {
        "sora_regular": (args.sora_regular, "Sora"),
        "sora_semibold": (args.sora_semibold, "Sora"),
        "atkinson_regular": (args.atkinson_regular, "Atkinson Hyperlegible Next"),
        "atkinson_medium": (args.atkinson_medium, "Atkinson Hyperlegible Next"),
        "atkinson_bold": (args.atkinson_bold, "Atkinson Hyperlegible Next"),
    }
    # Fully validate before changing any tracked file.
    for source, family in pairs.values():
        validate_font(source, family)
    validate_license(args.sora_license)
    validate_license(args.atkinson_license)
    manifest = {"fonts": {}, "licenses": {}}
    DEST.mkdir(parents=True, exist_ok=True)
    LICENCES.mkdir(parents=True, exist_ok=True)
    for name, (source, _) in pairs.items():
        target = DEST / (name + source.suffix.lower())
        shutil.copyfile(source, target)
        manifest["fonts"][target.name] = hashlib.sha256(target.read_bytes()).hexdigest()
    for name, source in [
        ("SORA-OFL.txt", args.sora_license),
        ("ATKINSON-HYPERLEGIBLE-NEXT-OFL.txt", args.atkinson_license),
    ]:
        target = LICENCES / name
        shutil.copyfile(source, target)
        manifest["licenses"][name] = hashlib.sha256(target.read_bytes()).hexdigest()
    BRAND_FONTS.write_text(generated_typefaces(), encoding="utf-8")
    (DEST / "halo-brand-font-manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print("Local brand fonts installed. Review the changes, build the app and commit the resources.")


if __name__ == "__main__":
    main()
